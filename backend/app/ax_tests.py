def habit_level(score: int) -> int:
    return max(i for i, (lo, *_) in enumerate(HABIT_LEVELS) if score >= lo)


def habit_score(answers: list[int]) -> dict:
    """answers: 문항 순서대로 0~3. → {score, level, dims{키: 0~100}, strong, weak, next[3]}"""
    sums: dict[str, list[int]] = {k: [] for k, *_ in HABIT_DIMS}
    for (dim, _), a in zip(HABIT_QUESTIONS, answers):
        sums[dim].append(a)
    dims = {k: round(sum(v) / (3 * len(v)) * 100) for k, v in sums.items()}
    score = round(sum(answers) / (3 * len(answers)) * 100)
    order = [k for k, *_ in HABIT_DIMS]
    ranked = sorted(order, key=lambda k: (dims[k], order.index(k)))  # 약한 순 (같으면 앞 영역)
    weak, weak2, strong = ranked[0], ranked[1], ranked[-1]
    nxt = HABIT_TIPS[weak][:2] + HABIT_TIPS[weak2][:1]
    return {"score": score, "level": habit_level(score), "dims": dims, "strong": strong, "weak": weak, "next": nxt}


