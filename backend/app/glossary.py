LEVELS = [(0, "🌱", "AI 새싹"), (40, "🌿", "AI 입문자"), (60, "🌳", "AI 실무자"), (80, "🚀", "AI 고수"), (100, "👑", "AI 마스터")]


def level(pct: float) -> tuple[str, str]:
    emoji, name = LEVELS[0][1:]
    for limit, e, n in LEVELS:
        if pct >= limit:
            emoji, name = e, n
    return emoji, name


FORMATS = 3  # 설명 → 용어 · 용어 → 설명 · 비유 → 용어


def questions(track: str, n: int = 10, seed: str | int | None = None) -> list[dict]:
    """[{q, prompt, options, answer, term, define, hint}] — 세 가지 출제 방식을 번갈아 낸다."""
    rng = random.Random(seed)
    terms = TERMS[track]
    picked = rng.sample(terms, min(n, len(terms)))
    out = []
    for i, (term, define, hint) in enumerate(picked):
        wrong = rng.sample([t for t in terms if t[0] != term], 3)
        kind = i % FORMATS
        if kind == 1:  # 용어 → 설명
            opts = [define] + [w[1] for w in wrong]
            q, prompt, answer = f"'{term}'의 뜻은?", f"비유하자면 — {hint}", define
        else:  # 설명 → 용어, 비유 → 용어
            opts = [term] + [w[0] for w in wrong]
            q, prompt, answer = (("이 설명에 맞는 용어는?", define, term) if kind == 0
                                 else ("이 비유가 가리키는 용어는?", f"💡 {hint}", term))
        rng.shuffle(opts)
        out.append({"q": q, "prompt": prompt, "options": opts, "answer": answer, "term": term, "define": define, "hint": hint})
    return out


def term_of_day(day_iso: str) -> tuple[str, tuple[str, str, str]]:
    """날짜마다 바뀌는 '오늘의 용어' (트랙, 용어)."""
    rng = random.Random(f"term:{day_iso}")
    track = rng.choice(list(TERMS))
    return track, rng.choice(TERMS[track])
